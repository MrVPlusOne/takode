import { exec as execCb } from "node:child_process";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { CALLER_CWD_ENV } from "../shared/bun-command-launch.js";
import { GIT_CMD_TIMEOUT, SERVER_GIT_CMD } from "./constants.js";

export const COMPANION_BIN_DIR = join(homedir(), ".companion", "bin");
export const LOCAL_BIN_DIR = join(homedir(), ".local", "bin");

/**
 * Set to the job id in every command `takode exec` runs. Such a command has
 * no session identity, so the session-aware CLIs refuse to run in it instead
 * of failing obscurely (no Bun, or the host port's 401) or acting unattributed.
 */
export const TAKODE_EXEC_JOB_ENV = "TAKODE_EXEC_JOB";
/** CLIs whose server calls are attributed to the calling session. */
const SESSION_CLIS = new Set(["quest", "memory", "stream", "takode"]);

/**
 * Resolve the stable repository root for shared CLI dispatchers.
 * Worktree-local package roots are mapped back to the main checkout so shared
 * wrappers stay valid after the worktree is archived.
 */
function execStdout(command: string, cwd: string): Promise<string> {
  return new Promise((resolve, reject) => {
    execCb(
      command,
      {
        cwd,
        encoding: "utf-8",
        timeout: GIT_CMD_TIMEOUT,
        maxBuffer: 64 * 1024,
      },
      (error, stdout) => {
        if (error) {
          reject(error);
          return;
        }
        resolve(stdout);
      },
    );
  });
}

export async function resolveStableWrapperRepoRoot(packageRoot: string): Promise<string> {
  return (await resolveGitRepoRoot(packageRoot)) ?? dirname(packageRoot);
}

export async function resolveStableWrapperScriptPath(packageRoot: string, commandName: string): Promise<string> {
  const stableRepoRoot = await resolveGitRepoRoot(packageRoot);
  return stableRepoRoot
    ? join(stableRepoRoot, "web", "bin", `${commandName}.ts`)
    : join(packageRoot, "bin", `${commandName}.ts`);
}

async function resolveGitRepoRoot(packageRoot: string): Promise<string | null> {
  try {
    const gitCommonDir = (await execStdout(`${SERVER_GIT_CMD} rev-parse --git-common-dir`, packageRoot)).trim();
    return gitCommonDir === ".git" ? dirname(packageRoot) : dirname(resolve(packageRoot, gitCommonDir));
  } catch {
    return null;
  }
}

function buildBunExec(commandName: string, scriptPath: string): string {
  // Start Bun from the Takode web folder, not the caller's directory: Bun lists every folder above its
  // working directory when it starts, which takes seconds under a huge one. bin/caller-cwd.ts switches back.
  const bunArgs = `--cwd "${dirname(dirname(scriptPath))}" "${scriptPath}" "$@"`;
  return `export ${CALLER_CWD_ENV}="$PWD"

if command -v bun >/dev/null 2>&1; then
  exec bun ${bunArgs}
fi

if [ -x "$HOME/.bun/bin/bun" ]; then
  export PATH="$HOME/.bun/bin:$PATH"
  exec "$HOME/.bun/bin/bun" ${bunArgs}
fi

echo "${commandName}: bun not found (looked in PATH and \\$HOME/.bun/bin/bun)" >&2
exit 127
`;
}

/** Second line of every installed CLI wrapper; it lets a wrapper recognize another Takode home's copy of itself. */
export const INSTALLED_CLI_WRAPPER_MARKER = "# Auto-generated by Companion server. Do not edit.";

export function buildInstalledCliWrapper(commandName: string, scriptPath: string): string {
  const execGuard = SESSION_CLIS.has(commandName)
    ? `if [ -n "$${TAKODE_EXEC_JOB_ENV}" ]; then
  echo "${commandName}: takode exec carries no session identity; run it from your own session" >&2
  exit 1
fi

`
    : "";
  return `#!/bin/bash
${INSTALLED_CLI_WRAPPER_MARKER}
${execGuard}${buildBunExec(commandName, scriptPath)}`;
}
